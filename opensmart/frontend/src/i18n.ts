export function language(settings: Settings): Lang {
  return settings.platform_language === 'es-MX' ? 'es-MX' : 'en';
}

export function t(settings: Settings | Lang, key: string, fallback: string): string {
  const lang = typeof settings === 'string' ? settings : language(settings);
  if (lang === 'es-MX') return es[key] || fallback;
  return fallback;
}

